/**
 * Look up guide content by slug. The map is keyed by arbitrary slug, so a miss
 * is a normal outcome rather than an error.
 */
export function findGuideContent(slug: string): GuideContent | undefined {
  if (!Object.hasOwn(GUIDE_CONTENT, slug)) {
    return undefined
  }

  // SAFETY: `Object.hasOwn` above proved `slug` is a key of GUIDE_CONTENT, so this
  // assertion only narrows a key that was already verified to exist.
  return GUIDE_CONTENT[slug as keyof typeof GUIDE_CONTENT]
}

